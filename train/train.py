#!/usr/bin/env python3
"""Train a tiny char-level Llama-style model (RMSNorm, RoPE, multi-query
attention, SwiGLU, tied embeddings) and export it as int8 C arrays."""
import math, sys, time, struct
import torch, torch.nn as nn, torch.nn.functional as F

# Fixed character set - must match hal.c
VOCAB = "\n !',-.0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz~#@*"
STOI = {c: i for i, c in enumerate(VOCAB)}

DIM, LAYERS, HEADS, KV_HEADS, HIDDEN, CTX = 96, 5, 4, 1, 288, 128
HD = DIM // HEADS
GS = 32  # quantization group size

class Block(nn.Module):
    def __init__(s):
        super().__init__()
        s.n1 = nn.Parameter(torch.ones(DIM)); s.n2 = nn.Parameter(torch.ones(DIM))
        s.wq = nn.Linear(DIM, DIM, bias=False)
        s.wk = nn.Linear(DIM, KV_HEADS*HD, bias=False)
        s.wv = nn.Linear(DIM, KV_HEADS*HD, bias=False)
        s.wo = nn.Linear(DIM, DIM, bias=False)
        s.w1 = nn.Linear(DIM, HIDDEN, bias=False)
        s.w3 = nn.Linear(DIM, HIDDEN, bias=False)
        s.w2 = nn.Linear(HIDDEN, DIM, bias=False)

def rms(x, w):
    return x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + 1e-5) * w

def rope(x, cos, sin):  # x: B,T,H,HD  (interleaved pairs)
    x0, x1 = x[..., 0::2], x[..., 1::2]
    return torch.stack([x0*cos - x1*sin, x0*sin + x1*cos], -1).flatten(-2)

class Model(nn.Module):
    def __init__(s):
        super().__init__()
        s.emb = nn.Embedding(len(VOCAB), DIM)
        s.blocks = nn.ModuleList([Block() for _ in range(LAYERS)])
        s.nf = nn.Parameter(torch.ones(DIM))
        f = 1.0 / (10000 ** (torch.arange(0, HD, 2).float() / HD))
        t = torch.arange(CTX).float()[:, None] * f[None]
        s.register_buffer("cos", t.cos()[None, :, None, :])
        s.register_buffer("sin", t.sin()[None, :, None, :])
        for p in s.parameters():
            if p.dim() == 2: nn.init.normal_(p, 0, 0.02)

    def forward(s, idx):
        B, T = idx.shape
        x = s.emb(idx)
        c, sn = s.cos[:, :T], s.sin[:, :T]
        for b in s.blocks:
            h = rms(x, b.n1)
            q = rope(b.wq(h).view(B, T, HEADS, HD), c, sn)
            k = rope(b.wk(h).view(B, T, KV_HEADS, HD), c, sn)
            v = b.wv(h).view(B, T, KV_HEADS, HD)
            k = k.expand(B, T, HEADS, HD); v = v.expand(B, T, HEADS, HD)
            a = F.scaled_dot_product_attention(q.transpose(1, 2), k.transpose(1, 2),
                                               v.transpose(1, 2), is_causal=True)
            x = x + b.wo(a.transpose(1, 2).reshape(B, T, DIM))
            h = rms(x, b.n2)
            x = x + b.w2(F.silu(b.w1(h)) * b.w3(h))
        return rms(x, s.nf) @ s.emb.weight.T


def train(corpus, steps, out):
    torch.manual_seed(0); torch.set_num_threads(2)
    text = open(corpus).read()
    data = torch.tensor([STOI[c] for c in text], dtype=torch.long)
    m = Model()
    print("params", sum(p.numel() for p in m.parameters()))
    opt = torch.optim.AdamW(m.parameters(), lr=3e-3, weight_decay=0.05, betas=(0.9, 0.95))
    B = 48; t0 = time.time()
    for it in range(steps + 1):
        lr = 3e-3 * min(1, (it + 1) / 200) * (0.1 + 0.9 * 0.5 * (1 + math.cos(math.pi * it / steps)))
        for g in opt.param_groups: g["lr"] = lr
        ix = torch.randint(len(data) - CTX - 1, (B,))
        x = torch.stack([data[i:i+CTX] for i in ix]); y = torch.stack([data[i+1:i+CTX+1] for i in ix])
        loss = F.cross_entropy(m(x).view(-1, len(VOCAB)), y.view(-1))
        opt.zero_grad(); loss.backward()
        torch.nn.utils.clip_grad_norm_(m.parameters(), 1.0); opt.step()
        if it % 200 == 0:
            print(f"{it} loss {loss.item():.3f} {time.time()-t0:.0f}s", flush=True)
    torch.save(m.state_dict(), out)
    return m


# ------------------------------------------------------------------ export
def q8(w):  # w: out x in  -> int8 + per-group scales (along input dim)
    w = w.detach().float()
    g = w.view(w.shape[0], -1, GS)
    s = g.abs().amax(-1, keepdim=True).clamp(min=1e-8) / 127.0
    q = torch.round(g / s).clamp(-127, 127).to(torch.int8)
    return q.flatten().tolist(), s.flatten().tolist()

def carr(name, typ, vals, per=24):
    fmt = (lambda v: f"{v:.7g}f") if typ == "float" else str
    lines = [", ".join(fmt(v) for v in vals[i:i+per]) for i in range(0, len(vals), per)]
    return f"static const {typ} {name}[{len(vals)}] = {{\n" + ",\n".join(lines) + "\n};\n"

def export(m, path):
    sd = m.state_dict()
    out = ["// Auto-generated by train.py - HAL tiny model weights\n#pragma once\n#include <stdint.h>\n",
           f"#define M_DIM {DIM}\n#define M_LAYERS {LAYERS}\n#define M_HEADS {HEADS}\n",
           f"#define M_KV_HEADS {KV_HEADS}\n#define M_HIDDEN {HIDDEN}\n#define M_CTX {CTX}\n",
           f"#define M_VOCAB {len(VOCAB)}\n#define M_GS {GS}\n",
           "static const char M_CHARS[] = " + '"' + VOCAB.replace("\\", "\\\\").replace("\n", "\\n").replace('"', '\\"') + '";\n']
    q, s = q8(sd["emb.weight"]); out += [carr("emb_q", "int8_t", q), carr("emb_s", "float", s)]
    for nm in ["n1", "n2", "wq", "wk", "wv", "wo", "w1", "w2", "w3"]:
        if nm in ("n1", "n2"):
            v = torch.cat([sd[f"blocks.{l}.{nm}"] for l in range(LAYERS)]).tolist()
            out.append(carr(nm, "float", v))
        else:
            qs, ss = [], []
            for l in range(LAYERS):
                q, s = q8(sd[f"blocks.{l}.{nm}.weight"]); qs += q; ss += s
            out += [carr(nm + "_q", "int8_t", qs), carr(nm + "_s", "float", ss)]
    out.append(carr("nf", "float", sd["nf"].tolist()))
    open(path, "w").write("".join(out))
    print("wrote", path)


@torch.no_grad()
def sample(m, prompt, n=120, temp=0.6):
    idx = torch.tensor([[STOI.get(c, 1) for c in prompt]])
    for _ in range(n):
        logits = m(idx[:, -CTX:])[0, -1] / temp
        nx = torch.multinomial(F.softmax(logits, -1), 1)
        idx = torch.cat([idx, nx[None]], 1)
        if VOCAB[nx.item()] == "\n": break
    return "".join(VOCAB[i] for i in idx[0].tolist())


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "train":
        m = train("corpus.txt", int(sys.argv[2]), "model.pt")
    else:
        m = Model(); m.load_state_dict(torch.load("model.pt"))
    m.eval()
    for p in ["U: what is the fuel status\nH:", "U: how much memory is left\nH:", "U: status report\nH:", "U: tell me about jupiter\nH:", "U: i am hungry\nH:", "U: are you conscious\nH:", "U: who are you\nH:", "U: open the pod bay doors\nH:", "U: are you afraid\nH:",
              "U: what is the mission\nH:", "U: i like turtles\nH:", "U: sing for me\nH:"]:
        print(repr(sample(m, p)))
    export(m, "../src/hal_model.h")
